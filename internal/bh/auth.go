// Package auth provides seamless login/integration for model providers.
// It stores credentials securely and handles OAuth flows for providers
// that support them, so the user never needs to manually export API keys.
package bh

import (
	"crypto/rand"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sync"
	"time"
)

// ProviderCredentials holds authentication credentials for a provider.
// Supports both API key auth and OAuth flows.
type ProviderCredentials struct {
	AccessToken  string `json:"access_token,omitempty"`
	RefreshToken string `json:"refresh_token,omitempty"`
	ExpiresAt    int64  `json:"expires_at,omitempty"`
	TokenType    string `json:"token_type,omitempty"`
	Scope        string `json:"scope,omitempty"`
	Account      string `json:"account,omitempty"`
	APIKey       string `json:"api_key,omitempty"`
	AuthMethod   string `json:"auth_method,omitempty"`
	TargetHost   string `json:"target_host,omitempty"`
}

const (
	AuthMethodAPIKey = "api_key"
	AuthMethodOAuth  = "oauth"
)

// AuthStore manages provider credentials.
// Credentials are stored in ~/.bhbadharness/credentials.json (0600 permissions).
type AuthStore struct {
	mu    sync.RWMutex
	dir   string
	path  string
	creds map[string]ProviderCredentials
}

// NewAuthStore creates a new auth store in the user's config directory.
func NewAuthStore() (*AuthStore, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return nil, err
	}
	dir := filepath.Join(home, ".bhbadharness", "credentials")
	if err := os.MkdirAll(dir, 0700); err != nil {
		return nil, err
	}
	path := filepath.Join(dir, "credentials.json")
	a := &AuthStore{
		dir:   dir,
		path:  path,
		creds: map[string]ProviderCredentials{},
	}
	// Load existing credentials
	if data, err := os.ReadFile(path); err == nil {
		var loaded map[string]ProviderCredentials
		if err := json.Unmarshal(data, &loaded); err != nil {
			// corrupted file, backup and start fresh
			backup := path + ".corrupt-" + time.Now().Format("20060102150405")
			os.Rename(path, backup)
		} else {
			a.creds = loaded
		}
	}
	return a, nil
}

// Save stores credentials for a provider.
// Files created by this method have 0600 permissions.
func (a *AuthStore) Save(provider string, creds ProviderCredentials) error {
	a.mu.Lock()
	defer a.mu.Unlock()

	a.creds[provider] = creds
	data, err := json.MarshalIndent(a.creds, "", "  ")
	if err != nil {
		return err
	}
	// Write to temp file then rename for atomicity
	tmp := a.path + ".tmp"
	if err := os.WriteFile(tmp, data, 0600); err != nil {
		return err
	}
	return os.Rename(tmp, a.path)
}

// Get retrieves credentials for a provider.
func (a *AuthStore) Get(provider string) (ProviderCredentials, bool) {
	a.mu.RLock()
	defer a.mu.RUnlock()
	creds, ok := a.creds[provider]
	return creds, ok
}

// Delete removes credentials for a provider.
func (a *AuthStore) Delete(provider string) error {
	a.mu.Lock()
	defer a.mu.Unlock()
	delete(a.creds, provider)
	data, err := json.MarshalIndent(a.creds, "", "  ")
	if err != nil {
		return err
	}
	tmp := a.path + ".tmp"
	if err := os.WriteFile(tmp, data, 0600); err != nil {
		return err
	}
	return os.Rename(tmp, a.path)
}

// List returns all providers with saved credentials.
func (a *AuthStore) List() []string {
	a.mu.RLock()
	defer a.mu.RUnlock()
	providers := make([]string, 0, len(a.creds))
	for p := range a.creds {
		providers = append(providers, p)
	}
	return providers
}

// GenState generates a cryptographically random state token for OAuth flows.
func GenState() (string, error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return fmt.Sprintf("%x", b), nil
}

// ValidateState checks if a state token is valid (was generated by GenState).
func ValidateState(state string) bool {
	if len(state) != 64 {
		return false
	}
	for _, c := range state {
		if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F')) {
			return false
		}
	}
	return true
}
